using System;
using System.Diagnostics;
using System.Text;
using System.Threading.Tasks;

namespace Task4_CountVowels
{
    internal class Program
    {
        /* Задача 4

            Условие:
            Даден е дълъг текст.
            Да се преброи колко гласни букви съдържа текстът,
            независимо дали буквите са главни или малки.

            Гласните букви, които трябва да проверяваме, са:
            а, ъ, о, у, е, и

            Изисквания:
            - Създайте дълъг текст, като повторите 500 000 пъти
              изречението:

              "Асинхронно програмиране. "

            - За всеки символ:
              1. Превърнете го в малка буква с char.ToLower()
              2. Проверете дали се среща в низа "аъоуеи"

            - Реализирайте блокиращо решение –
              обработката се извиква директно в Main().

            - Реализирайте неблокиращо решение –
              обработката се пуска с Task.Run(),
              а резултатът се изчаква с await.

            - Изведете резултата и времето за изпълнение
              на двата варианта, като използвате Stopwatch.
        */


        // async ни позволява да използваме await в Main().
        //
        // Task означава, че Main може да изпълнява
        // асинхронни операции.
        static async Task Main(string[] args)
        {
            // Създаваме изречението,
            // което трябва да повторим 500 000 пъти.
            string sentence = "Асинхронно програмиране. ";


            // Създаваме обект от тип StringBuilder.
            //
            // StringBuilder се използва, когато искаме
            // многократно да добавяме текст.
            //
            // Той е по-подходящ от обикновен string,
            // защото при всяко добавяне не се създава
            // изцяло нов string в паметта.
            //
            // В началото StringBuilder-ът е празен.
            StringBuilder text = new StringBuilder();


            // Този цикъл ще се изпълни 500 000 пъти.
            //
            // При всяко завъртане добавяме
            // изречението sentence към StringBuilder-а text.
            for (int i = 0; i < 500_000; i++)
            {
                // Append() добавя подадения текст
                // в края на StringBuilder-а.
                //
                // В случая добавяме sentence
                // към вече натрупания текст.
                //
                // За разлика от string,
                // тук не използваме:
                //
                // text = text + sentence;
                //
                // а използваме Append(),
                // защото text е StringBuilder.
                text.Append(sentence);
            }


            // Създаваме Stopwatch,
            // с който ще измерваме времето
            // за изпълнение на двата варианта.
            Stopwatch stopwatch = new Stopwatch();


            // =========================================
            // ВАРИАНТ 1: БЛОКИРАЩО ИЗПЪЛНЕНИЕ
            // =========================================


            // Стартираме измерването на времето.
            stopwatch.Start();


            // Извикваме метода директно.
            //
            // Подаваме StringBuilder-а text
            // като параметър на метода.
            //
            // Това е блокиращ вариант, защото Main()
            // няма да продължи към следващия ред,
            // докато CountVowels() не приключи.
            int blockingCount = CountVowels(text);


            // След като методът приключи,
            // спираме измерването на времето.
            stopwatch.Stop();


            Console.WriteLine("Блокиращо изпълнение:");

            // Принтираме колко гласни букви
            // са намерени в целия текст.
            Console.WriteLine($"Брой гласни букви: {blockingCount}");

            // Принтираме времето за изпълнение.
            Console.WriteLine($"Време: {stopwatch.ElapsedMilliseconds} ms");


            // =========================================
            // ВАРИАНТ 2: НЕБЛОКИРАЩО ИЗПЪЛНЕНИЕ
            // =========================================


            // Restart() прави две неща:
            //
            // 1. Нулира старото измерено време.
            // 2. Стартира Stopwatch отново.
            stopwatch.Restart();


            // Task.Run() стартира метода CountVowels(text)
            // като отделна задача чрез ThreadPool.
            //
            // await означава:
            //
            // "Изчакай задачата да приключи
            // и когато е готова, вземи резултата."
            //
            // Task.Run() -> "Пусни тази работа."
            // await      -> "Когато приключи, продължи оттук."
            int asyncCount = await Task.Run(() =>
            {
                return CountVowels(text);
            });


            // След като асинхронната задача приключи,
            // спираме измерването на времето.
            stopwatch.Stop();


            Console.WriteLine();

            Console.WriteLine("Неблокиращо изпълнение:");

            // Принтираме резултата,
            // който сме получили от Task.Run().
            Console.WriteLine($"Брой гласни букви: {asyncCount}");

            // Принтираме времето за изпълнение.
            Console.WriteLine($"Време: {stopwatch.ElapsedMilliseconds} ms");
        }


        // Този метод преброява колко гласни букви
        // има в подадения текст.
        //
        // Методът приема един параметър:
        //
        // StringBuilder text
        // -> StringBuilder обектът,
        //    който съдържа целия текст.
        //
        // StringBuilder позволява да достъпваме
        // отделните символи чрез индекс,
        // по подобен начин както при string.
        //
        // Методът връща int,
        // защото резултатът е БРОЙ намерени гласни.
        static int CountVowels(StringBuilder text)
        {
            // Създаваме променлива vowels,
            // в която записваме всички гласни букви,
            // които трябва да търсим.
            //
            // По условие това са:
            // а, ъ, о, у, е, и
            string vowels = "аъоуеи";


            // Създаваме брояч,
            // който ще пази броя на намерените гласни.
            //
            // В началото той е 0,
            // защото все още не сме проверили
            // нито един символ.
            int count = 0;


            // Обхождаме целия StringBuilder
            // символ по символ.
            //
            // text.Length ни дава броя
            // на всички символи, които в момента
            // се съдържат в StringBuilder-а.
            for (int i = 0; i < text.Length; i++)
            {
                // Вземаме текущия символ
                // от StringBuilder-а чрез индекс.
                //
                // StringBuilder позволява достъп
                // до символите подобно на string.
                //
                // Например:
                //
                // ако i = 0:
                // currentChar = text[0]
                //
                // ако i = 5:
                // currentChar = text[5]
                char currentChar = text[i];


                // char.ToLower() превръща буквата
                // в малка буква.
                //
                // Това ни позволява да не правим
                // отделни проверки за:
                //
                // 'А' и 'а'
                // 'О' и 'о'
                // и т.н.
                //
                // Например:
                //
                // char.ToLower('А') -> 'а'
                // char.ToLower('И') -> 'и'
                char lowerChar = char.ToLower(currentChar);


                // Contains() проверява дали даден символ
                // се съдържа в низа vowels.
                //
                // Например:
                //
                // vowels.Contains('а') -> true
                // vowels.Contains('о') -> true
                // vowels.Contains('б') -> false
                //
                // Ако текущият символ е гласна,
                // увеличаваме брояча.
                if (vowels.Contains(lowerChar))
                {
                    // count++ е същото като:
                    //
                    // count = count + 1;
                    count++;
                }
            }


            // След като сме проверили
            // всички символи в StringBuilder-а,
            // връщаме крайния брой гласни.
            return count;
        }
    }
}