
namespace GenericsTask3
{
    public class Item
    {
        // Този клас описва един предмет.
        //
        // Създаваме го, за да имаме тип,
        // с който да тестваме Generic метода.

        // Свойство, което пази името на предмета.

        public string Name { get; set; }

        // Това е конструктор без параметри.
        //
        // Той се извиква автоматично,
        // когато напишем:
        //
        // new Item()
        //
        // Ограничението where T : new()
        // позволява да използваме този конструктор.

        public Item()
        {
            // Всеки нов предмет получава
            // начално име "Нов предмет".

            Name = "Нов предмет";
        }

        // ToString() определя какво да се
        // показва, когато отпечатаме обекта.
        //
        // Без този метод Console.WriteLine(item)
        // обикновено ще отпечата името на класа.
        //
        // С този метод ще отпечата името
        // на конкретния предмет.

        public override string ToString()
        {
            return $"Предмет: {Name}";
        }
    }
}
