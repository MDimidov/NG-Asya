
using System.Collections.Generic;

namespace GenericsTask3
{
    public class ObjectCollection
    {
        // Какво е Generic метод?
        //
        // Представи си машина за създаване на предмети.
        //
        // Казваш на машината:
        // "Създай ми 3 предмета от тип Item."
        //
        // Тя създава точно 3 предмета.
        //
        // Ако поискаш друг тип, машината
        // може да създаде и него.
        //
        // Това е идеята на Generic метода.
        //
        // <T> означава, че типът се избира
        // при извикването на метода.
        //
        // Например:
        // CreateList<Item>(3)
        //
        // T = Item
        // count = 3

        // Какво означава where T : new()?
        //
        // Това е ограничение за типа T.
        //
        // То казва:
        // "Типът T трябва да може да се създава
        // чрез конструктор без параметри."
        //
        // Например:
        // new Item()
        //
        // Така можем безопасно да използваме new T().

        public static List<T> CreateList<T>(int count) where T : new()
        {
            // Стъпка 1:
            // Създаваме празен списък от тип T.
            //
            // Ако T е Item, това означава:
            // List<Item>
            //
            // В началото списъкът няма елементи. (празен е)

            List<T> items = new List<T>();

            // Стъпка 2:
            // Проверяваме дали count е отрицателно число.
            //
            // Не можем да създадем отрицателен
            // брой обекти.

            if (count < 0)
            {
                Console.WriteLine("Броят на обектите не може да е отрицателен. Върнат е празен лист.");
                return items;
            }

            // Стъпка 3:
            // Използваме for цикъл.
            //
            // Ако count = 3, цикълът ще се
            // изпълни точно 3 пъти.
            //
            // i = 0 -> първи обект
            // i = 1 -> втори обект
            // i = 2 -> трети обект

            for (int i = 0; i < count; i++)
            {
                // Стъпка 4:
                // Създаваме нов обект от тип T.
                //
                // Ако T е Item:
                // new T() означава new Item().
                //
                // Всеки път се създава нов обект.

                T newObject = new T();

                // Стъпка 5:
                // Добавяме новия обект в списъка.
                //
                // Add() поставя елемент
                // в края на списъка.

                items.Add(newObject);
            }

            // Стъпка 6:
            // Връщаме готовия списък.
            //
            // Ако count = 3, списъкът съдържа
            // точно 3 новосъздадени обекта.

            return items;
        }
    }
}
