
using System;
using System.Diagnostics;
using System.Threading.Tasks;

namespace ArraySumTask
{
    internal class Program
    {

        /* Задача 1
            Условие:
            Даден е масив от 10 000 000 цели числа. Да се намери сборът на всичките му елементи
            Изисквания:
            - Запълнете масива с числата 1, 2, ..., 1000, после отново 1, 2, ..., 1000 и т.н
              Подсказка:
              arr[i] = i % 1000 + 1;
            - Сборът е по-голям от границата на int, затова го пазете в променлива от тип long
            - Реализирайте блокиращо решение – обработката се извиква директно в Main()
            - Реализирайте неблокиращо решение – обработката се пуска с Task.Run(), а резултатът се изчаква с await
            - Изведете резултата и времето за изпълнение на двата варианта, като използвате Stopwatch
        */


        // async позволява да използваме await в Main().
        // Task означава, че методът поддържа асинхронно изпълнение.
        static async Task Main(string[] args)
        {
            // Създаваме масив с 10 милиона цели числа.
            // Всеки елемент първоначално има стойност 0.
            int[] arr = new int[10_000_000];

            // Запълваме масива с числата от 1 до 1000,
            // след което последователността се повтаря.
            for (int i = 0; i < arr.Length; i++)
            {
                // % намира остатъка от целочислено деление.
                // Например:
                // i = 0    -> 0 % 1000 + 1 = 1
                // i = 999  -> 999 % 1000 + 1 = 1000
                // i = 1000 -> 1000 % 1000 + 1 = 1
                arr[i] = i % 1000 + 1;
            }

            // Stopwatch измерва времето за изпълнение.
            Stopwatch stopwatch = new Stopwatch();

            // =========================================
            // ВАРИАНТ 1: БЛОКИРАЩО ИЗПЪЛНЕНИЕ
            // =========================================

            // Стартираме измерването на времето.
            stopwatch.Start();

            // Извикваме метода директно.
            // Main изчаква методът да приключи,
            // преди да премине към следващия ред.
            long blockingSum = CalculateSum(arr);

            // Спираме измерването.
            stopwatch.Stop();

            Console.WriteLine("Блокиращо изпълнение:");
            Console.WriteLine($"Сбор: {blockingSum}");
            Console.WriteLine($"Време: {stopwatch.ElapsedMilliseconds} ms");

            // =========================================
            // ВАРИАНТ 2: НЕБЛОКИРАЩО ИЗПЪЛНЕНИЕ
            // =========================================

            // Нулираме Stopwatch, за да измерим
            // времето на втория вариант отначало.
            stopwatch.Restart();

            // Task.Run() изпраща изчислението
            // за изпълнение чрез ThreadPool.
            //
            // await изчаква резултата асинхронно,
            // без да блокира текущата нишка.

            // Асинхронно означава: „Не стой и не чакай безсмислено.
            // Докато една работа се върши, може да се прави и нещо друго“

            // С други думи Task.Run казва: Пусни тази задача отделно
            // await казва: Когато приключи, върни ме тук и продължи
            long asyncSum = await Task.Run(() =>
            {
                return CalculateSum(arr);
            });

            // Спираме измерването.
            stopwatch.Stop();

            Console.WriteLine();
            Console.WriteLine("Неблокиращо изпълнение:");
            Console.WriteLine($"Сбор: {asyncSum}");
            Console.WriteLine($"Време: {stopwatch.ElapsedMilliseconds} ms");
        }

        // Метод, който намира сбора на всички
        // елементи в подадения масив.
        //
        // Използваме long, защото сборът може
        // да надвиши максималната стойност на int.
        static long CalculateSum(int[] numbers)
        {
            // long може да съхранява много по-големи
            // цели числа от int.
            long sum = 0;

            // foreach обхожда всеки елемент от масива.
            // На всяка итерация number съдържа
            // стойността на текущия елемент.
            foreach (int number in numbers)
            {
                // Добавяме текущото число към сбора.
                sum += number;
            }

            // Връщаме крайния сбор.
            return sum;
        }
    }
}
