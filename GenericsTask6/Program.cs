
using System;
using System.Collections.Generic;

namespace GenericsTask6
{
    internal class Program
    {
        /*
         * Задача 6
         *
         * Условие:
         * Създайте шаблонен метод
         * BuildDictionary<TKey, TValue>(
         *     TKey[] keys,
         *     TValue[] values)
         *
         * Ограничения:
         * where TKey : notnull
         * where TValue : struct
         *
         * Методът трябва да върне Dictionary<TKey, TValue>
         * с двойките ключ–стойност.
         *
         * Пример:
         * string[] keys = { "A", "B", "C" };
         * int[] vals = { 1, 2, 3 };
         *
         * var dict = BuildDictionary(keys, vals);
         *
         * Резултат:
         * A -> 1
         * B -> 2
         * C -> 3
         */

        static void Main(string[] args)
        {
            // Стъпка 1:
            // Създаваме масив с ключове.
            //
            // Всеки ключ е текст (string).
            //
            // Ключовете ще използваме, за да
            // намираме съответните им стойности.

            string[] keys = { "A", "B", "C" };

            // Стъпка 2:
            // Създаваме масив със стойности.
            //
            // Всяка стойност е цяло число (int).
            //
            // Елементите от двата масива
            // ще бъдат свързани по индекс.
            //
            // keys[0] = "A" -> values[0] = 1
            // keys[1] = "B" -> values[1] = 2
            // keys[2] = "C" -> values[2] = 3

            int[] values = { 1, 2, 3 };

            // Стъпка 3:
            // Извикваме Generic метода.
            //
            // Той ще създаде Dictionary,
            // като свърже всеки ключ
            // със съответната му стойност.
            //
            // Компилаторът автоматично разбира:
            //
            // TKey   = string
            // TValue = int

            Dictionary<string, int> dict = BuildDictionary(keys, values);


            // Стъпка 4:
            // Отпечатваме съдържанието на Dictionary.
            //
            // foreach обхожда всяка двойка ключ–стойност.
            //
            // Какво е var
            //
            // var е ключова дума, която позволява
            // на C# автоматично да определи типа
            // на променливата.
            //
            // Например:
            // var number = 10;       -> int
            // var text = "Hello";    -> string
            // var price = 5.5;       -> double
            //
            // Важно:
            // var НЕ означава, че променливата
            // може свободно да сменя типа си.
            //
            // След като C# определи типа,
            // той остава същият.
            //
            // В нашия пример:
            //
            // dict е Dictionary<string, int>.
            //
            // Всеки негов елемент представлява
            // двойка ключ–стойност от тип:
            //
            // KeyValuePair<string, int>
            //
            // Следователно:
            //
            // foreach (var pair in dict)
            //
            // е същото като:
            //
            // foreach (KeyValuePair<string, int> pair in dict)
            //
            // Използваме var, защото е по-кратко
            // и C# вече знае типа на елементите.
            //
            // pair.Key   -> ключът (например "A")
            // pair.Value -> стойността (например 1)
            //
            // При всяко завъртане на цикъла
            // pair съдържа следващата двойка.
            //
            // Първо: A -> 1
            // После: B -> 2
            // После: C -> 3

            foreach (var pair in dict)
            {
                Console.WriteLine($"{pair.Key} -> {pair.Value}");
            }


            Console.WriteLine();

            // Стъпка 5:
            // Можем да намерим стойност
            // директно чрез нейния ключ.
            //
            // Например:
            // dict["B"] връща числото 2.
            //
            // Това е една от основните
            // причини да използваме Dictionary.

            Console.WriteLine($"Стойност на B: {dict["B"]}");
            Console.WriteLine($"Стойност на A: {dict["A"]}");
        }

        /*
         * КАКВО Е DICTIONARY В C#?
         *
         * Представи си истински речник.
         *
         * В него имаме дума и нейното значение.
         *
         * Например:
         *
         * Куче  -> Животно
         * Ябълка -> Плод
         * Синьо -> Цвят
         *
         * Dictionary работи по подобен начин.
         *
         * Той съхранява информация под формата
         * на двойки:
         *
         * КЛЮЧ -> СТОЙНОСТ
         *
         * На английски:
         * KEY -> VALUE
         *
         * Например:
         *
         * "Иван"  -> 5
         * "Петър" -> 6
         * "Мария" -> 4
         *
         * Имената са ключове.
         * Числата са стойности.
         *
         *
         * КАК СЕ СЪЗДАВА DICTIONARY?
         *
         * Dictionary<string, int> grades = new Dictionary<string, int>();
         *
         * string -> типът на ключа
         * int    -> типът на стойността
         *
         * Добавяме елементи чрез Add():
         *
         * grades.Add("Иван", 5);
         * grades.Add("Петър", 6);
         *
         * Четем стойност чрез ключа:
         *
         * Console.WriteLine(grades["Иван"]);
         *
         * Резултат: 5
         *
         *
         * ВАЖНИ ПРАВИЛА:
         *
         * 1. Всеки ключ трябва да е уникален.
         *
         * Например не можем да добавим:
         *
         * grades.Add("Иван", 5);
         * grades.Add("Иван", 6);
         *
         * Това ще предизвика грешка,
         * защото ключът "Иван" вече съществува.
         *
         * 2. Стойностите могат да се повтарят.
         *
         * Например:
         *
         * grades.Add("Иван", 5);
         * grades.Add("Мария", 5);
         *
         * Това е напълно позволено.
         *
         * 3. Dictionary използва ключове,
         * за да намира стойностите.
         *
         * За разлика от масива, при който
         * обикновено използваме индекс:
         *
         * numbers[0]
         *
         * При Dictionary използваме ключ:
         *
         * grades["Иван"]
         *
         *
         * КАКВО Е TKey И TValue?
         *
         * TKey е Generic типът на ключа.
         *
         * TValue е Generic типът на стойността.
         *
         * Например:
         *
         * Dictionary<string, int>
         *
         * TKey   = string
         * TValue = int
         *
         * Dictionary<int, double>
         *
         * TKey   = int
         * TValue = double
         *
         * Използваме два Generic типа,
         * защото ключът и стойността
         * могат да бъдат от различни типове.
         */

        static Dictionary<TKey, TValue> BuildDictionary<TKey, TValue>(TKey[] keys, TValue[] values) 
            where TKey : notnull
            where TValue : struct
        {
            // Какво означава where TKey : notnull
            //
            // Това ограничение казва,
            // че типът на ключа не трябва
            // да допуска null стойности.
            //
            // Например:
            // string -> позволен като non-nullable тип
            // int    -> позволен

            // Какво означава where TValue : struct
            //
            // Това ограничение казва,
            // че стойността трябва да бъде
            // тип данни, който е value type.
            //
            // Например:
            // int     -> позволен
            // double  -> позволен
            // bool    -> позволен
            // string  -> НЕ е позволен
            //
            // struct не означава само тип,
            // създаден с ключовата дума struct.
            //
            // int, double и bool също
            // са стойностни типове.

            // Стъпка 1:
            // Създаваме празен Dictionary.
            //
            // TKey определя типа на ключовете.
            // TValue определя типа на стойностите.
            //
            // В нашия пример това е:
            // Dictionary<string, int>

            Dictionary<TKey, TValue> dictionary = new Dictionary<TKey, TValue>();

            // Стъпка 2:
            // Проверяваме дали двата масива
            // имат еднаква дължина.
            //
            // Например:
            // keys   = { "A", "B", "C" }
            // values = { 1, 2 }
            //
            // Тук няма стойност за ключа "C".
            // Затова не можем да ги свържем правилно.

            if (keys.Length != values.Length)
            {
                Console.WriteLine("Двата масива трябва да са с еднаква дължина!");

                // Тук връщаме празния Dictionary, за да прекратим
                // изпълнението на останалата част от кода
                return dictionary;
            }

            // Стъпка 3:
            // Обхождаме масивите с for цикъл.
            //
            // Използваме един и същи индекс i,
            // за да вземем съответните елементи.
            //
            // Например:
            // i = 0 -> "A" и 1
            // i = 1 -> "B" и 2
            // i = 2 -> "C" и 3

            for (int i = 0; i < keys.Length; i++)
            {
                // Стъпка 4:
                // Добавяме двойката ключ–стойност.
                //
                // Add() приема два аргумента:
                //
                // Първи аргумент  -> ключ
                // Втори аргумент -> стойност
                //
                // Например при i = 0:
                //
                // dictionary.Add("A", 1);
                //
                // При i = 1:
                //
                // dictionary.Add("B", 2);
                //
                // Ако ключът вече съществува,
                // Add() ще предизвика грешка.

                dictionary.Add(keys[i], values[i]);
            }

            // Стъпка 5:
            // Връщаме готовия Dictionary.
            //
            // Той вече съдържа:
            //
            // A -> 1
            // B -> 2
            // C -> 3

            return dictionary;
        }
    }
}
