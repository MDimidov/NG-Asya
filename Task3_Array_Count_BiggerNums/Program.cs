using System;
using System.Diagnostics;
using System.Threading.Tasks;

namespace Task3_CountGreaterThanKTask
{
    internal class Program
    {
        /* Задача 3

            Условие:
            Даден е масив от 10 000 000 цели числа и число K.
            Да се преброи колко от числата в масива са по-големи от K.

            Изисквания:
            - Запълнете масива по същия начин като в задача 1:
              с числата 1, 2, ..., 1000, после отново
              1, 2, ..., 1000 и т.н.

              Подсказка:
              arr[i] = i % 1000 + 1;

            - За K задайте стойност 900.

            - Методът за броене трябва да приема:
              масива и K като параметри.

            - Реализирайте блокиращо решение –
              обработката се извиква директно в Main().

            - Реализирайте неблокиращо решение –
              обработката се пуска с Task.Run(),
              а резултатът се изчаква с await.

            - Изведете резултата и времето за изпълнение
              на двата варианта, като използвате Stopwatch.
        */


        // async ни позволява да използваме await в Main().
        //
        // Task означава, че Main може да изпълнява
        // асинхронни операции.
        static async Task Main(string[] args)
        {
            // Създаваме масив от 10 милиона цели числа.
            //
            // При създаването на масива всички негови
            // стойности първоначално са 0.
            int[] arr = new int[10_000_000];


            // Запълваме масива с числата:
            //
            // 1, 2, 3, ..., 1000,
            // след това отново:
            // 1, 2, 3, ..., 1000
            // и така до края на масива.
            for (int i = 0; i < arr.Length; i++)
            {
                // Операторът % връща остатъка от делението.
                //
                // Примери:
                //
                // i = 0
                // 0 % 1000 = 0
                // 0 + 1 = 1
                //
                // i = 899
                // 899 % 1000 = 899
                // 899 + 1 = 900
                //
                // i = 900
                // 900 % 1000 = 900
                // 900 + 1 = 901
                //
                // i = 999
                // 999 % 1000 = 999
                // 999 + 1 = 1000
                //
                // i = 1000
                // 1000 % 1000 = 0
                // 0 + 1 = 1

                arr[i] = i % 1000 + 1;
            }


            // Създаваме променлива K.
            //
            // Задачата изисква да преброим
            // колко числа в масива са ПО-ГОЛЕМИ от K.
            int k = 900;


            // Създаваме Stopwatch,
            // с който ще измерваме времето
            // за изпълнение на двата варианта.
            Stopwatch stopwatch = new Stopwatch();


            // =========================================
            // ВАРИАНТ 1: БЛОКИРАЩО ИЗПЪЛНЕНИЕ
            // =========================================


            // Стартираме измерването на времето.
            stopwatch.Start();


            // Извикваме метода директно.
            //
            // Подаваме му:
            // 1. arr -> масива
            // 2. k   -> числото, с което ще сравняваме
            //
            // Това е блокиращ вариант, защото Main()
            // няма да продължи към следващия ред,
            // докато CountGreaterThanK() не приключи.
            int blockingCount = CountGreaterThanK(arr, k);


            // След като методът приключи,
            // спираме измерването на времето.
            stopwatch.Stop();


            Console.WriteLine("Блокиращо изпълнение:");

            // Принтираме стойността на K.
            Console.WriteLine($"K = {k}");

            // Принтираме колко числа в масива
            // са по-големи от K.
            Console.WriteLine($"Брой числа по-големи от K: {blockingCount}");

            // Принтираме времето за изпълнение.
            Console.WriteLine($"Време: {stopwatch.ElapsedMilliseconds} ms");


            // =========================================
            // ВАРИАНТ 2: НЕБЛОКИРАЩО ИЗПЪЛНЕНИЕ
            // =========================================


            // Restart() прави две неща:
            //
            // 1. Нулира старото измерено време.
            // 2. Стартира Stopwatch отново.
            stopwatch.Restart();


            // Task.Run() стартира метода
            // CountGreaterThanK(arr, k)
            // като отделна задача чрез ThreadPool.
            //
            // await означава:
            //
            // "Изчакай задачата да приключи
            // и когато е готова, вземи резултата."
            //
            // Task.Run() -> "Пусни тази работа."
            // await      -> "Когато приключи, продължи оттук."
            int asyncCount = await Task.Run(() =>
            {
                return CountGreaterThanK(arr, k);
            });


            // След като асинхронната задача приключи,
            // спираме измерването на времето.
            stopwatch.Stop();


            Console.WriteLine();

            Console.WriteLine("Неблокиращо изпълнение:");

            // Принтираме стойността на K.
            Console.WriteLine($"K = {k}");

            // Принтираме резултата,
            // който сме получили от Task.Run().
            Console.WriteLine($"Брой числа по-големи от K: {asyncCount}");

            // Принтираме времето за изпълнение.
            Console.WriteLine($"Време: {stopwatch.ElapsedMilliseconds} ms");
        }


        // Този метод преброява колко числа
        // в дадения масив са по-големи от K.
        //
        // Методът приема два параметъра:
        //
        // int[] numbers
        // -> масивът, който ще обхождаме
        //
        // int k
        // -> числото, с което ще сравняваме
        //
        // Методът връща int,
        // защото резултатът е БРОЙ елементи.
        static int CountGreaterThanK(int[] numbers, int k)
        {
            // Създаваме променлива count,
            // която ще пази броя на намерените числа,
            // които са по-големи от K.
            //
            // В началото броят е 0,
            // защото все още не сме проверили
            // нито един елемент.
            int count = 0;


            // Обхождаме целия масив
            // от първия до последния елемент.
            for (int i = 0; i < numbers.Length; i++)
            {
                // Вземаме текущия елемент от масива
                // и го запазваме в отделна променлива.
                //
                // Например:
                //
                // ако i = 0:
                // currentNumber = numbers[0]
                //
                // ако i = 5:
                // currentNumber = numbers[5]
                int currentNumber = numbers[i];


                // Проверяваме дали текущото число
                // е ПО-ГОЛЯМО от K.
                //
                // В нашия случай K = 900.
                //
                // Например:
                //
                // 850 > 900 -> false
                // 900 > 900 -> false
                // 901 > 900 -> true
                // 1000 > 900 -> true
                if (currentNumber > k)
                {
                    // Ако условието е вярно,
                    // увеличаваме брояча с 1.
                    //
                    // count++ е същото като:
                    //
                    // count = count + 1;
                    count++;
                }
            }


            // След като сме проверили
            // всички елементи от масива,
            // връщаме крайния брой.
            return count;
        }
    }
}