
using System;
using System.Collections.Generic;
using TLArchNUnit_Task5_MovieTheater.Data;

namespace TLArchNUnit_Task5_MovieTheater.Business
{
    // BUSINESS LAYER (Слой за логика)
    //
    // Тук пишем правилата на нашия киносалон.
    //
    // Този клас отговаря за:
    //
    // 1. Добавяне на филми.
    // 2. Намиране на филма с най-висок рейтинг.
    // 3. Намиране на филми от определен жанр,
    //    които са по-кратки от зададени минути.

    public class MovieManager
    {
        // МЕТОД 1: AddMovie()
        //
        // Получава филм и го добавя
        // към списъка на киносалона.
        //
        // bool означава, че методът връща:
        //
        // true  -> успешно добавяне
        // false -> неуспешно добавяне
        //
        // Преди да добавим филма, проверяваме:
        //
        // 1. Съществува ли филмът?
        // 2. Има ли заглавие?
        // 3. Има ли жанр?
        // 4. Продължителността положителна ли е?
        // 5. Рейтингът между 1 и 10 ли е?
        //
        // Така не позволяваме в списъка
        // да попадат невалидни филми.

        public bool AddMovie(Movie movie)
        {
            // null означава, че няма обект.
            //
            // Ако не съществува филм,
            // няма какво да добавим.

            if (movie == null)
            {
                return false;
            }

            // Проверяваме дали заглавието е празно.
            //
            // string.IsNullOrWhiteSpace() проверява
            // дали текстът е празен или съдържа
            // само интервали.

            if (string.IsNullOrWhiteSpace(movie.Title))
            {
                return false;
            }

            // Проверяваме дали има въведен жанр.

            if (string.IsNullOrWhiteSpace(movie.Genre))
            {
                return false;
            }

            // Продължителността трябва
            // да бъде положително число.
            //
            // Например:
            // 90  -> валидно
            // 0   -> невалидно
            // -20 -> невалидно

            if (movie.DurationMinutes <= 0)
            {
                return false;
            }

            // Рейтингът трябва да бъде
            // между 1 и 10 включително.
            //
            // || означава ИЛИ.
            //
            // Ако рейтингът е под 1
            // ИЛИ над 10, връщаме false.
            //
            // double.IsNaN() проверява за
            // специална стойност "Not a Number",
            // която не е истински рейтинг.

            if (double.IsNaN(movie.Rating) ||
                movie.Rating < 1 || movie.Rating > 10)
            {
                return false;
            }

            // Ако всички проверки са успешни,
            // добавяме филма в списъка.
            //
            // Add() добавя нов елемент.

            MovieData.Movies.Add(movie);

            return true;
        }

        // МЕТОД 2: GetTopRatedMovie()
        //
        // Търсим филма с най-висок рейтинг.
        //
        // Например:
        //
        // Avatar    -> 8.5
        // Titanic   -> 7.9
        // Inception -> 9.2
        //
        // Резултат: Inception
        //
        // Защото 9.2 е най-голямото число.

        public Movie? GetTopRatedMovie()
        {
            // Ако няма добавени филми,
            // връщаме null.
            //
            // Count показва колко филма
            // има в списъка.

            if (MovieData.Movies.Count == 0)
            {
                return null;
            }

            // Приемаме първия филм
            // за този с най-висок рейтинг.
            //
            // [0] означава първия елемент.
            //
            // В C# броенето започва от 0.

            Movie topMovie = MovieData.Movies[0];

            // foreach обхожда всички филми
            // един по един.

            foreach (Movie movie in MovieData.Movies)
            {
                // Сравняваме рейтингите.
                //
                // Ако текущият филм има
                // по-висок рейтинг,
                // запомняме него.

                if (movie.Rating > topMovie.Rating)
                {
                    topMovie = movie;
                }
            }

            // Връщаме намерения филм.

            return topMovie;
        }

        // МЕТОД 3: GetShortMoviesByGenre()
        //
        // Търсим филми, които отговарят
        // едновременно на две условия:
        //
        // 1. Имат определен жанр.
        // 2. По-кратки са от зададените минути.
        //
        // Например:
        //
        // Търсим жанр "Comedy"
        // и продължителност под 100 минути.
        //
        // Филм A -> Comedy, 90 минути
        // Филм B -> Comedy, 120 минути
        // Филм C -> Action, 80 минути
        // Филм D -> Comedy, 75 минути
        //
        // Резултат:
        // Филм A и Филм D
        //
        // Защото само те изпълняват
        // и двете условия.

        public List<Movie> GetShortMoviesByGenre(
            string genre, int maxMinutes)
        {
            // Създаваме празен списък.
            //
            // В него ще добавяме само филмите,
            // които отговарят на условията.

            List<Movie> result = new List<Movie>();

            // Проверяваме всеки филм.

            foreach (Movie movie in MovieData.Movies)
            {
                // && означава И.
                //
                // И двете условия трябва
                // да бъдат изпълнени.
                //
                // == проверява дали жанрът съвпада.
                //
                // < проверява дали времетраенето
                // е ПО-МАЛКО от maxMinutes.
                //
                // ВАЖНО:
                // Ако maxMinutes = 100:
                //
                // 99 минути  -> включва се
                // 100 минути -> НЕ се включва
                // 101 минути -> НЕ се включва

                if (movie.Genre == genre &&
                    movie.DurationMinutes < maxMinutes)
                {
                    // Добавяме намерения филм
                    // в списъка с резултати.

                    result.Add(movie);
                }
            }

            // Връщаме намерените филми.
            //
            // Ако няма подходящи филми,
            // списъкът ще бъде празен.

            return result;
        }
    }
}
