
using System;

namespace GenericsTask1
{
    internal class Program
    {
        /*
         * Задача 1
         *
         * Условие:
         * Създайте шаблонен метод GetLength<T>,
         * който приема един аргумент от тип T.
         *
         * Методът трябва:
         * 1. Да приема стойности от различни типове.
         * 2. Да превръща подадената стойност в текст чрез ToString().
         * 3. Да намира дължината на получения текст.
         * 4. Да извежда стойността и типа на аргумента.
         * 5. Да връща дължината на текста.
         *
         * Пример:
         * GetLength("Програмиране") -> 12
         * GetLength(12345) -> 5
         */

        static void Main(string[] args)
        {
            // Извикваме метода с текст (string).
            // T автоматично става string.
            Console.WriteLine(GetLength("Програмиране"));

            Console.WriteLine();

            // Извикваме същия метод с цяло число (int).
            // Този път T автоматично става int.
            Console.WriteLine(GetLength(12345));

            // Извикваме същия метод с дробно число (double).
            // Този път T автоматично става int.
            Console.WriteLine(GetLength(0012345.000260));
        }

        // Какво е Generic метод?
        //
        // Представи си, че имаш кутия, в която можеш
        // да поставяш различни предмети.
        //
        // Generic методът работи по подобен начин.
        // Може да приема различни типове данни,
        // без да пишем отделен метод за всеки тип.
        //
        // <T> означава, че използваме тип,
        // който ще бъде определен при извикването.
        //
        // Например:
        // GetLength("Hello") -> T е string
        // GetLength(123)     -> T е int
        // GetLength(3.14)    -> T е double

        static int GetLength<T>(T arg)
        {
            // Стъпка 1:
            // Превръщаме подадената стойност в текст.
            //
            // Например:
            // 12345 -> "12345"
            //
            // ToString() превръща стойността в текст.
            // ?. предпазва от грешка, ако arg е null.
            // ?? "" използва празен текст при null.

            string text = arg?.ToString() ?? "";

            // Стъпка 2:
            // Намираме колко символа има текстът.
            //
            // Например:
            // "12345" -> 5 символа
            // "Hello" -> 5 символа

            int length = text.Length;

            // Стъпка 3:
            // Извеждаме оригиналната стойност.

            Console.WriteLine($"Стойност: {arg}");

            // Стъпка 4:
            // typeof(T) ни показва типа на T.
            // Може също да се ползва също arg.GetType()
            //
            //
            // Например:
            // string -> System.String
            // int    -> System.Int32

            Console.WriteLine($"Тип: {typeof(T)}");
            Console.WriteLine($"Тип: {arg.GetType()}");

            // Стъпка 5:
            // return връща намерената дължина.
            //
            // Тъй като методът е от тип int,
            // той трябва да върне цяло число.

            return length;
        }
    }
}
