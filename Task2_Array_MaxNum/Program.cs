using System;
using System.Diagnostics;
using System.Threading.Tasks;

namespace ArrayMaxTask
{
    internal class Program
    {
        /* Задача 2
            Условие:
            Даден е масив от 10 000 000 цели числа.
            Да се намери най-голямото число в масива.

            Изисквания:
            - Запълнете масива по същия начин като в задача 1:
              с числата 1, 2, ..., 1000, после отново 1, 2, ..., 1000 и т.н.

              Подсказка:
              arr[i] = i % 1000 + 1;

            - За намиране на най-голямото число:
              приемете първия елемент за най-голям
              и го сравнявайте с всеки от останалите.

            - Реализирайте блокиращо решение –
              обработката се извиква директно в Main().

            - Реализирайте неблокиращо решение –
              обработката се пуска с Task.Run(),
              а резултатът се изчаква с await.

            - Изведете резултата и времето за изпълнение
              на двата варианта, като използвате Stopwatch.
        */


        // async ни позволява да използваме await в Main().
        // Task означава, че Main може да изпълнява асинхронни операции.
        static async Task Main(string[] args)
        {
            // Създаваме масив от 10 милиона цели числа.
            // При създаването всички стойности първоначално са 0.
            int[] arr = new int[10_000_000];


            // Запълваме масива с числата:
            // 1, 2, 3, ..., 1000,
            // след това отново 1, 2, 3, ..., 1000 и т.н.
            for (int i = 0; i < arr.Length; i++)
            {
                // % връща остатъка от делението.

                // Примери:
                // i = 0
                // 0 % 1000 = 0
                // 0 + 1 = 1

                // i = 999
                // 999 % 1000 = 999
                // 999 + 1 = 1000

                // i = 1000
                // 1000 % 1000 = 0
                // 0 + 1 = 1

                arr[i] = i % 1000 + 1;
            }


            // Създаваме Stopwatch,
            // с който ще измерваме времето за изпълнение.
            Stopwatch stopwatch = new Stopwatch();


            // =========================================
            // ВАРИАНТ 1: БЛОКИРАЩО ИЗПЪЛНЕНИЕ
            // =========================================

            // Стартираме измерването на времето.
            stopwatch.Start();


            // Извикваме метода директно.
            //
            // Това е блокиращ вариант, защото Main()
            // няма да продължи към следващия ред,
            // докато FindMax() не приключи напълно.
            int blockingMax = FindMax(arr);


            // Спираме Stopwatch,
            // защото изчислението вече е приключило.
            stopwatch.Stop();


            Console.WriteLine("Блокиращо изпълнение:");

            // Показваме най-голямото намерено число.
            Console.WriteLine($"Най-голямо число: {blockingMax}");

            // Показваме времето,
            // необходимо за изпълнение на операцията.
            Console.WriteLine($"Време: {stopwatch.ElapsedMilliseconds} ms");


            // =========================================
            // ВАРИАНТ 2: НЕБЛОКИРАЩО ИЗПЪЛНЕНИЕ
            // =========================================


            // Restart() прави две неща:
            // 1. Нулира старото измерено време
            // 2. Стартира Stopwatch отново
            stopwatch.Restart();


            // Task.Run() стартира FindMax(arr)
            // като отделна задача чрез ThreadPool.
            //
            // await казва:
            // "Изчакай тази задача да приключи,
            // и когато е готова, вземи резултата."
            //
            // Асинхронно означава:
            // "Не стой и не чакай безсмислено.
            // Докато една работа се извършва,
            // може да се извършва и друга работа."
            //
            // Task.Run() -> "Пусни тази работа."
            // await      -> "Когато приключи, продължи оттук."
            int asyncMax = await Task.Run(() =>
            {
                return FindMax(arr);
            });


            // Спираме измерването.
            stopwatch.Stop();


            Console.WriteLine();

            Console.WriteLine("Неблокиращо изпълнение:");

            // Принтираме резултата от асинхронната задача.
            Console.WriteLine($"Най-голямо число: {asyncMax}");

            // Принтираме времето за изпълнение.
            Console.WriteLine($"Време: {stopwatch.ElapsedMilliseconds} ms");
        }


        // Този метод намира най-голямото число
        // в подадения масив.
        //
        // Методът е static, защото го извикваме
        // директно от static Main().
        static int FindMax(int[] numbers)
        {
            // Приемаме, че първият елемент
            // в масива е най-големият.
            //
            // Това е по-добър вариант от:
            //
            // int max = 0;
            //
            // защото ако масивът съдържа само
            // отрицателни числа, 0 може изобщо
            // да не присъства в масива.
            int max = numbers[0];


            // Започваме от индекс 1,
            // защото индекс 0 вече сме го използвали
            // като начална стойност на max.
            for (int i = 1; i < numbers.Length; i++)
            {
                // Проверяваме дали текущото число
                // е по-голямо от най-голямото,
                // което сме намерили до момента.
                if (numbers[i] > max)
                {
                    // Ако е по-голямо,
                    // записваме го като новото най-голямо число.
                    max = numbers[i];
                }
            }


            // Връщаме най-голямото намерено число.
            return max;
        }
    }
}