
using System;

namespace GenericsTask5
{
    internal class Program
    {
        /*
         * Задача 5
         *
         * Условие:
         * Създайте шаблонен метод SwapArrays<T>(T[] array1, T[] array2),
         * който разменя елементите на двата масива индекс по индекс.
         *
         * Двата масива трябва да са с еднаква дължина.
         *
         * Пример:
         * int[] array1 = { 1, 2, 3 };
         * int[] array2 = { 4, 5, 6 };
         * SwapArrays(array1, array2);
         *
         * Резултат:
         * array1 = { 4, 5, 6 }
         * array2 = { 1, 2, 3 }
         */

        static void Main(string[] args)
        {
            // Създаваме два масива от цели числа.

            int[] array1 = { 1, 2, 3 };
            int[] array2 = { 4, 5, 6 };

            // След като го решиш сама пробавй вместо int да ползваш string
            //string[] array1 = { "масив", "номер", "едно(А)" };
            //string[] array2 = { "това", "е масив", "две(Б)" };

            // Отпечатваме масивите преди размяната.

            Console.WriteLine("Преди размяната:");

            // Използваме метода PrintArray(), за да отпечатаме
            // всеки елемент от първия масив.

            Console.Write("Масив A: ");

            PrintArray<int>(array1);

            // Отпечатваме втория масив.

            Console.Write("Масив B: ");

            PrintArray<int>(array2);

            Console.WriteLine();

            // Извикваме Generic метода.

            SwapArrays<int>(array1, array2);

            // Отпечатваме масивите след размяната.

            Console.WriteLine("След размяната:");

            Console.Write("Масив A: ");

            PrintArray<int>(array1);

            Console.Write("Масив B: ");

            PrintArray<int>(array2);
        }

        // Какво означава <T>
        //
        // T е заместител на тип данни.
        //
        // Например:
        // SwapArrays(int[], int[])       -> T е int
        // SwapArrays(string[], string[]) -> T е string
        //
        // Така един метод може да разменя
        // елементите на масиви от различни типове.

        // Какво означава T[]?
        //
        // T  -> типът на елементите
        // [] -> означава масив
        //
        // T[] означава масив от тип T.

        static void SwapArrays<T>(T[] array1, T[] array2)
        {
            // Стъпка 1:
            // Проверяваме дали масивите
            // имат еднаква дължина.

            if (array1.Length != array2.Length)
            {
                Console.WriteLine("Грешка! Масивите трябва да са с еднаква дължина.");

                // Прекратяваме метода,
                // без да разменяме елементите.

                return;
            }

            // Стъпка 2:
            // Обхождаме масивите с for цикъл.
            //
            // Например:
            // Индекс:    0  1  2
            // Масив A: { 1, 2, 3 }
            // Масив B: { 4, 5, 6 }

            for (int i = 0; i < array1.Length; i++)
            {
                // Стъпка 3:
                // Запазваме стойността от първия масив
                // във временна променлива.
                //
                // При i = 0:
                // temp = 1

                T temp = array1[i];

                // Стъпка 4:
                // Копираме стойността от втория масив
                // в първия.
                //
                // При i = 0:
                // array1[0] = 4

                array1[i] = array2[i];

                // Стъпка 5:
                // Поставяме запазената стойност
                // във втория масив.
                //
                // При i = 0:
                // array2[0] = 1

                array2[i] = temp;

                // Цикълът повтаря тези действия
                // за всеки следващ индекс.
            }

            // Методът е void, защото променяме
            // директно елементите на масивите.
        }

        static void PrintArray<T>(T[] array)
        {
            for (int i = 0; i < array.Length; i++)
            {
                // Write отпечатва стойността,
                // без да преминава на нов ред.

                Console.Write( array[i] + " " );
            }

            // След като отпечатаме всички елементи от масива
            // принираме нов ред в конзолата
            Console.WriteLine();
        }
    }
}
