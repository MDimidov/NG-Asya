
using System;
using System.Collections.Generic;
using TLArchNUnit_Task4_FitnessCenter.Data;

namespace TLArchNUnit_Task4_FitnessCenter.Business
{
    // BUSINESS LAYER (Слой за логика)
    //
    // Тук пишем правилата на фитнес залата.
    //
    // Този клас отговаря за:
    //
    // 1. Добавяне на нов клиент.
    // 2. Намиране на клиента с най-много
    //    оставащи дни от абонамента.
    // 3. Изчисляване на общите месечни такси
    //    за определен тип абонамент.

    public class FitnessManager
    {
        // МЕТОД 1: AddMember()
        //
        // Получава клиент и го добавя
        // в списъка на фитнес залата.
        //
        // bool означава, че методът връща:
        //
        // true  -> успешно добавяне
        // false -> неуспешно добавяне
        //
        // Проверяваме дали клиентът съществува.
        //
        // За да не записваме грешни данни,
        // проверяваме също:
        //
        // - Има ли въведено име?
        // - Абонаментът месечен или годишен е?
        // - Оставащите дни отрицателни ли са?
        // - Месечната такса отрицателна ли е?

        public bool AddMember(Member member)
        {
            // Ако няма създаден клиент,
            // няма какво да добавяме.
            //
            // null означава, че няма обект.

            if (member == null)
            {
                return false;
            }

            // Проверяваме дали името е празно.
            //
            // string.IsNullOrWhiteSpace() проверява
            // дали текстът е празен или съдържа
            // само интервали.

            if (string.IsNullOrWhiteSpace(member.Name))
            {
                return false;
            }

            // Разрешаваме два типа абонамент.
            //
            // && означава И.
            //
            // Ако типът НЕ е "Месечен"
            // И НЕ е "Годишен",
            // значи е невалиден.
            //
            // != означава "различно от".

            if (member.Type != "Месечен" && member.Type != "Годишен")
            {
                return false;
            }

            // Не можем да имаме отрицателен
            // брой оставащи дни.
            //
            // 0 дни е допустимо - означава,
            // че абонаментът е изтекъл.

            if (member.DaysRemaining < 0)
            {
                return false;
            }

            // Цената също не може
            // да бъде отрицателна.

            if (member.MonthlyFee < 0)
            {
                return false;
            }

            // Ако всички проверки са успешни,
            // добавяме клиента към списъка.

            FitnessData.Members.Add(member);

            return true;
        }

        // МЕТОД 2: GetMemberWithMostDays()
        //
        // Търсим клиента с най-много
        // оставащи дни от абонамента.
        //
        // Например:
        //
        // Иван   -> 25 дни
        // Мария  -> 300 дни
        // Георги -> 120 дни
        //
        // Резултат: Мария
        //
        // Защото 300 е най-голямото число.

        public Member? GetMemberWithMostDays()
        {
            // Ако няма клиенти,
            // връщаме null.
            //
            // Count показва колко елемента
            // има в списъка.

            if (FitnessData.Members.Count == 0)
            {
                return null;
            }

            // Приемаме първия клиент
            // за този с най-много оставащи дни.
            //
            // [0] означава първия елемент.

            Member memberWithMostDays = FitnessData.Members[0];

            // foreach обхожда всеки клиент
            // в списъка един по един.

            foreach (Member member in FitnessData.Members)
            {
                // Сравняваме оставащите дни.
                //
                // Ако текущият клиент има
                // повече оставащи дни,
                // запомняме него.

                if (member.DaysRemaining > memberWithMostDays.DaysRemaining)
                {
                    memberWithMostDays = member;
                }
            }

            // След като проверим всички,
            // връщаме намерения клиент.

            return memberWithMostDays;
        }

        // МЕТОД 3: GetTotalRevenueByType()
        //
        // Изчисляваме общата сума от
        // месечните такси за определен
        // вид абонамент.
        //
        // Например:
        //
        // Иван   -> Месечен -> 60 лв.
        // Мария  -> Годишен -> 40 лв.
        // Георги -> Месечен -> 70 лв.
        //
        // Търсим: "Месечен"
        //
        // Резултат:
        // 60 + 70 = 130 лв.
        //
        // НЕ добавяме таксата на Мария,
        // защото тя има годишен абонамент.
        //
        // ВАЖНО:
        // Тук събираме стойностите MonthlyFee.
        // Това е сбор на месечните такси,
        // а не реално отчетени плащания.

        public decimal GetTotalRevenueByType(string type)
        {
            // Създаваме променлива,
            // в която ще събираме таксите.
            //
            // В началото сборът е 0.

            decimal totalRevenue = 0;

            // Проверяваме всеки клиент.

            foreach (Member member in FitnessData.Members)
            {
                // == означава сравнение.
                //
                // Ако типът на абонамента
                // съвпада с търсения,
                // добавяме месечната такса.

                if (member.Type == type)
                {
                    // += добавя стойност
                    // към текущия сбор.
                    //
                    // Например:
                    // totalRevenue = 60
                    // добавяме 70
                    // totalRevenue става 130.

                    totalRevenue += member.MonthlyFee;
                }
            }

            // Връщаме общия сбор.
            //
            // Ако няма клиенти от този тип,
            // резултатът ще бъде 0.

            return totalRevenue;
        }
    }
}
