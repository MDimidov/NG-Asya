
using System;
using System.Collections.Generic;
using TLArchNUnit_Task3_StudentManagement.Data;

namespace TLArchNUnit_Task3_StudentManagement.Business
{
    // BUSINESS LAYER (Слой за логика)
    //
    // Тук пишем правилата на нашата система.
    //
    // Този клас отговаря за:
    //
    // 1. Добавяне на студент с валиден успех.
    // 2. Намиране на студента с най-висок успех.
    // 3. Намиране на студенти от определен курс
    //    с успех над 4.50.

    public class StudentManager
    {
        // МЕТОД 1: AddStudent()
        //
        // Получава студент и проверява
        // дали успехът му е валиден.
        //
        // Валидни оценки са:
        // 2.00, 3.00, 4.50, 5.75, 6.00
        //
        // Невалидни оценки са:
        // 1.50, 6.50, -2
        //
        // bool означава, че методът връща:
        //
        // true  -> студентът е добавен
        // false -> студентът не е добавен

        public bool AddStudent(Student student)
        {
            // Проверяваме дали имаме студент.
            //
            // null означава, че няма обект.
            //
            // || означава ИЛИ.
            //
            // Ако студентът не съществува
            // ИЛИ успехът е под 2
            // ИЛИ успехът е над 6,
            // няма да го добавим.

            if (student == null || student.Grade < 2 || student.Grade > 6)
            {
                return false;
            }

            // Add() добавя студента
            // в общия списък.

            StudentData.Students.Add(student);

            return true;
        }

        // МЕТОД 2: GetTopStudent()
        //
        // Търсим студента с най-висок успех.
        //
        // Например:
        //
        // Иван   -> 4.50
        // Мария  -> 5.75
        // Георги -> 5.25
        //
        // Резултат: Мария
        //
        // Защото 5.75 е най-високият успех.

        public Student? GetTopStudent()
        {
            // Ако списъкът е празен,
            // няма студент за намиране.
            //
            // Count показва колко студенти
            // има в списъка.

            if (StudentData.Students.Count == 0)
            {
                return null;
            }

            // Приемаме първия студент
            // за студент с най-висок успех.
            //
            // [0] означава първия елемент.
            //
            // В C# броенето започва от 0.

            Student topStudent = StudentData.Students[0];

            // foreach обхожда всеки студент
            // в списъка един по един.

            foreach (Student student in StudentData.Students)
            {
                // Ако текущият студент
                // има по-висок успех,
                // запомняме него.

                if (student.Grade > topStudent.Grade)
                {
                    topStudent = student;
                }
            }

            // След като проверим всички,
            // връщаме студента с най-висок успех.

            return topStudent;
        }

        // МЕТОД 3: GetExcellentStudentsByCourse()
        //
        // Получава курс като число.
        //
        // Например: 2
        //
        // Търсим всички студенти,
        // които отговарят на ДВЕ условия:
        //
        // 1. Учат във втори курс.
        // 2. Имат успех над 4.50.
        //
        // Например:
        //
        // Иван   -> курс 2, успех 5.50
        // Мария  -> курс 2, успех 4.00
        // Георги -> курс 3, успех 6.00
        // Петър  -> курс 2, успех 5.00
        //
        // Резултат:
        // Иван и Петър
        //
        // Защото само те изпълняват
        // и двете условия.

        public List<Student> GetExcellentStudentsByCourse(int course)
        {
            // Създаваме празен списък.
            //
            // В него ще добавяме само
            // студентите, които отговарят
            // на условията.

            List<Student> result = new List<Student>();

            // Проверяваме всеки студент.

            foreach (Student student in StudentData.Students)
            {
                // && означава И.
                //
                // Това означава, че и двете
                // условия трябва да са изпълнени.
                //
                // == проверява дали курсът съвпада.
                //
                // > проверява дали успехът
                // е строго по-голям от 4.50.
                //
                // ВАЖНО:
                // 4.50 не се включва!
                // 4.51 се включва!

                if (student.Course == course && student.Grade > 4.50)
                {
                    // Добавяме намерения студент
                    // в списъка с резултати.

                    result.Add(student);
                }
            }

            // Връщаме намерените студенти.
            //
            // Ако няма подходящи студенти,
            // списъкът ще бъде празен.

            return result;
        }
    }
}
