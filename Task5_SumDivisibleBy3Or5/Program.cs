using System;
using System.Diagnostics;
using System.Threading.Tasks;

namespace Task5_SumDivisibleBy3Or5
{
    internal class Program
    {
        /* Задача 5

            Условие:
            Да се намери сборът на всички естествени числа
            от 1 до N, които се делят на 3 или на 5.

            Например:
            ако N = 10, числата са:

            3, 5, 6, 9 и 10

            Сборът им е:

            3 + 5 + 6 + 9 + 10 = 33

            Изисквания:
            - Задайте N = 100 000 000.

            - Използвайте цикъл от 1 до N.

            - Проверявайте дали текущото число
              се дели на 3 ИЛИ на 5 чрез:

              i % 3 == 0 || i % 5 == 0

            - Сборът трябва да се пази в променлива
              от тип long.

            - Проверете програмата първо с N = 10.
              Трябва да получите резултат 33.

            - Реализирайте блокиращо решение –
              обработката се извиква директно в Main().

            - Реализирайте неблокиращо решение –
              обработката се пуска с Task.Run(),
              а резултатът се изчаква с await.

            - Изведете резултата и времето за изпълнение
              на двата варианта, като използвате Stopwatch.
        */


        // async ни позволява да използваме await в Main().
        //
        // Task означава, че Main може да изпълнява
        // асинхронни операции.
        static async Task Main(string[] args)
        {
            // Създаваме променлива N.
            //
            // Тя определя до кое число
            // трябва да извършваме проверките.
            //
            // По условие N трябва да бъде:
            //
            // 100 000 000
            int n = 100_000_000;


            // За проверка на програмата можем временно
            // да използваме:
            //
            // int n = 10;
            //
            // Тогава резултатът трябва да бъде 33.


            // Създаваме Stopwatch,
            // с който ще измерваме времето
            // за изпълнение на двата варианта.
            Stopwatch stopwatch = new Stopwatch();


            // =========================================
            // ВАРИАНТ 1: БЛОКИРАЩО ИЗПЪЛНЕНИЕ
            // =========================================


            // Стартираме измерването на времето.
            stopwatch.Start();


            // Извикваме метода директно.
            //
            // Подаваме n като параметър,
            // за да знае методът до кое число
            // трябва да обхожда.
            //
            // Това е блокиращ вариант, защото Main()
            // няма да продължи към следващия ред,
            // докато SumDivisibleBy3Or5() не приключи.
            long blockingSum = SumDivisibleBy3Or5(n);


            // След като методът приключи,
            // спираме измерването на времето.
            stopwatch.Stop();


            Console.WriteLine("Блокиращо изпълнение:");

            // Принтираме стойността на N.
            Console.WriteLine($"N = {n}");

            // Принтираме получения сбор.
            Console.WriteLine($"Сбор: {blockingSum}");

            // Принтираме времето за изпълнение.
            Console.WriteLine($"Време: {stopwatch.ElapsedMilliseconds} ms");


            // =========================================
            // ВАРИАНТ 2: НЕБЛОКИРАЩО ИЗПЪЛНЕНИЕ
            // =========================================


            // Restart() прави две неща:
            //
            // 1. Нулира старото измерено време.
            // 2. Стартира Stopwatch отново.
            stopwatch.Restart();


            // Task.Run() стартира метода
            // SumDivisibleBy3Or5(n)
            // като отделна задача чрез ThreadPool.
            //
            // await означава:
            //
            // "Изчакай задачата да приключи
            // и когато е готова, вземи резултата."
            //
            // Task.Run() -> "Пусни тази работа."
            // await      -> "Когато приключи, продължи оттук."
            long asyncSum = await Task.Run(() =>
            {
                return SumDivisibleBy3Or5(n);
            });


            // След като асинхронната задача приключи,
            // спираме измерването на времето.
            stopwatch.Stop();


            Console.WriteLine();

            Console.WriteLine("Неблокиращо изпълнение:");

            // Принтираме стойността на N.
            Console.WriteLine($"N = {n}");

            // Принтираме резултата,
            // който сме получили от Task.Run().
            Console.WriteLine($"Сбор: {asyncSum}");

            // Принтираме времето за изпълнение.
            Console.WriteLine($"Време: {stopwatch.ElapsedMilliseconds} ms");
        }


        // Този метод намира сбора
        // на всички естествени числа от 1 до N,
        // които се делят на 3 или на 5.
        //
        // Методът приема един параметър:
        //
        // int n
        // -> числото, до което трябва
        //    да извършваме проверките.
        //
        // Методът връща long,
        // защото сборът може да стане
        // прекалено голям за int.
        static long SumDivisibleBy3Or5(int n)
        {
            // Създаваме променлива sum,
            // която ще пази общия сбор.
            //
            // Използваме long,
            // защото резултатът може да бъде
            // по-голям от максималната стойност на int.
            //
            // В началото сборът е 0,
            // защото все още не сме добавили нито едно число.
            long sum = 0;


            // Обхождаме всички естествени числа
            // от 1 до N включително.
            //
            // Започваме от 1,
            // защото по условие разглеждаме
            // естествените числа от 1 до N.
            //
            // Използваме <=,
            // защото трябва да проверим и самото N.
            for (int i = 1; i <= n; i++)
            {
                // Проверяваме дали текущото число
                // се дели без остатък на 3
                // ИЛИ се дели без остатък на 5.
                //
                // i % 3 == 0
                // означава:
                //
                // "Остатъкът при деление на 3 е 0."
                //
                // Това означава, че числото
                // се дели точно на 3.
                //
                // Същото важи и за:
                //
                // i % 5 == 0
                //
                // Операторът || означава "ИЛИ".
                //
                // Тоест е достатъчно
                // поне едното условие да е вярно.
                //
                // Примери:
                //
                // 3 % 3 == 0  -> true
                // 3 % 5 == 0  -> false
                //
                // true || false -> true
                //
                //
                // 5 % 3 == 0  -> false
                // 5 % 5 == 0  -> true
                //
                // false || true -> true
                //
                //
                // 7 % 3 == 0  -> false
                // 7 % 5 == 0  -> false
                //
                // false || false -> false
                if (i % 3 == 0 || i % 5 == 0)
                {
                    // Ако текущото число се дели
                    // на 3 или на 5,
                    // го добавяме към общия сбор.
                    //
                    // Това:
                    //
                    // sum += i;
                    //
                    // е същото като:
                    //
                    // sum = sum + i;
                    sum += i;
                }
            }


            // След като сме проверили
            // всички числа от 1 до N,
            // връщаме крайния сбор.
            return sum;
        }
    }
}